// RFC 1035 zone file builder. Pure function — used by both the real BIND driver
// and the dev simulator, and covered by unit tests.

function escapeTxt(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

export function buildZoneFile({ domain, records, serial, primaryNs, secondaryNs, adminEmail = 'hostmaster', defaultTtl = 3600 }) {
  const pad = (s, n) => String(s).padEnd(n);
  const lines = [];
  const email = adminEmail.includes('@') ? adminEmail.replace('@', '.') : adminEmail;

  lines.push(`; Generated by G-Panel — DO NOT EDIT MANUALLY`);
  lines.push(`; Zone: ${domain} | Serial: ${serial}`);
  lines.push(`$ORIGIN ${domain}.`);
  lines.push(`$TTL ${defaultTtl}`);
  lines.push('');
  lines.push(`@   IN  SOA ${primaryNs}. ${email}. (`);
  lines.push(`        ${pad(serial, 12)} ; serial (YYYYMMDDnn)`);
  lines.push(`        ${pad(7200, 12)} ; refresh`);
  lines.push(`        ${pad(3600, 12)} ; retry`);
  lines.push(`        ${pad(1209600, 12)} ; expire`);
  lines.push(`        ${pad(defaultTtl, 12)} ; minimum`);
  lines.push(`)`);
  lines.push('');

  // NS records always at apex
  lines.push(`; Name servers`);
  lines.push(`@   IN  NS  ${primaryNs}.`);
  if (secondaryNs && secondaryNs !== primaryNs) lines.push(`@   IN  NS  ${secondaryNs}.`);
  lines.push('');

  for (const r of records) {
    const name = r.name === '@' || r.name === domain ? '@' : r.name;
    const ttl = r.ttl ? ` ${r.ttl}` : '';
    const host = name === '@' ? '@' : `${name}`;
    let value = r.value;
    if (r.type === 'MX') {
      lines.push(`${pad(host, 24)}${pad(ttl, 7)} IN  MX  ${r.prio ?? 10}  ${value.endsWith('.') ? value : value + '.'}`);
      continue;
    }
    if (r.type === 'CNAME' || r.type === 'NS') {
      value = value.endsWith('.') ? value : value + '.';
    }
    if (r.type === 'TXT') {
      value = `"${escapeTxt(value)}"`;
    }
    lines.push(`${pad(host, 24)}${pad(ttl, 7)} IN  ${pad(r.type, 6)}  ${value}`);
  }
  return lines.join('\n') + '\n';
}

export function bumpSerial(currentSerial, now = new Date()) {
  const base = Number(
    `${now.getUTCFullYear()}${String(now.getUTCMonth() + 1).padStart(2, '0')}${String(now.getUTCDate()).padStart(2, '0')}00`
  );
  if (!currentSerial || currentSerial < base) return base;
  return currentSerial + 1;
}
