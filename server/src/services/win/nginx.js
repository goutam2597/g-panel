import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { runSafe } from '../../lib/exec.js';
import { config } from '../../config.js';

// nginx-for-Windows driver: the panel owns a stack copy (stack/nginx) with a
// generated nginx.conf that includes stack/nginx/gpanel-sites/*.conf.

const nginxDir = () => path.join(config.stackDir, 'nginx').replace(/\\/g, '/');
const sitesDir = () => path.join(nginxDir(), 'gpanel-sites');

function writeBaseConfig() {
  const dir = nginxDir();
  fs.mkdirSync(sitesDir(), { recursive: true });
  fs.mkdirSync(path.join(dir, 'logs'), { recursive: true });
  fs.mkdirSync(path.join(dir, 'temp'), { recursive: true });

  // Absolute paths everywhere: relative include/log paths resolve against the
  // conf directory on Windows and silently match nothing.
  const conf = [
    '# Generated by G-Panel — panel-owned nginx for Windows',
    'worker_processes  auto;',
    `error_log  ${dir}/logs/error.log;`,
    `pid        ${dir}/logs/nginx.pid;`,
    '',
    'events {',
    '    worker_connections  1024;',
    '}',
    '',
    'http {',
    `    include       ${dir}/conf/mime.types;`,
    '    default_type  application/octet-stream;',
    '    sendfile      on;',
    '    keepalive_timeout  65;',
    '    client_max_body_size 512m;',
    `    access_log  ${dir}/logs/access.log;`,
    '',
    `    include ${dir}/gpanel-sites/*.conf;`,
    '}'
  ].join('\n');
  fs.writeFileSync(path.join(dir, 'conf', 'nginx.conf'), conf);
  return true;
}

export default {
  async ensureRunning() {
    writeBaseConfig();
    const dir = nginxDir();
    if (!fs.existsSync(path.join(dir, 'nginx.exe'))) {
      throw new Error('nginx is not installed in the panel stack — run install-windows.ps1');
    }
    // detached: the master must outlive the panel process (nginx on Windows
    // stays foreground when inherited — without detached it dies with us)
    const child = spawn(dir + '/nginx.exe', ['-p', dir + '/', '-c', dir + '/conf/nginx.conf'], {
      cwd: dir, detached: true, stdio: 'ignore', windowsHide: true
    });
    child.unref();
    await new Promise((r) => setTimeout(r, 700));
    return true;
  },

  async writeVhost(opts) {
    // opts: {domain, user, type, docroot, phpVersion, forceHttps, proxyTarget, hasCert}
    writeBaseConfig();

    // create the docroot with a starter page so a new site resolves instantly
    fs.mkdirSync(opts.docroot, { recursive: true });
    const idx = path.join(opts.docroot, 'index.html');
    if (!fs.existsSync(idx)) {
      fs.writeFileSync(idx, `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${opts.domain}</title>
<style>body{font-family:Georgia,serif;max-width:44rem;margin:4rem auto;padding:0 1.5rem;color:#1a1c20;line-height:1.6}
.badge{display:inline-block;background:#0E6B5A;color:#fff;font-size:.75rem;letter-spacing:.08em;text-transform:uppercase;padding:.3rem .7rem;border-radius:3px}</style>
</head><body>
<span class="badge">Served by G-Panel on Windows</span>
<h1>${opts.domain}</h1>
<p>This site is served by nginx (panel-managed) from <code>${opts.docroot}</code>. Upload your files here via the file manager.</p>
</body></html>
`);
    }
    const logsDir = opts.docroot.replace(/\/public_html$/, '') + '/logs';
    fs.mkdirSync(logsDir, { recursive: true });

    // pick the FastCGI target for the requested PHP version (php-cgi pool)
    let fastcgiTarget;
    if (opts.type === 'php') {
      const { default: php } = await import('./php.js');
      fastcgiTarget = await php.targetFor(opts.phpVersion);
    }

    const file = path.join(sitesDir(), `${opts.domain}.conf`);
    const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    const { buildVhost } = await import('../../lib/vhost-template.js');
    const text = buildVhost({ ...opts, forceHttps: false, hasCert: false, fastcgiTarget, listenPort: config.webPort }); // TLS via Cloudflare edge locally
    fs.writeFileSync(file, text);

    const test = await runSafe(nginxDir() + '/nginx.exe', ['-p', nginxDir() + '/', '-c', 'conf/nginx.conf', '-t'], { cwd: nginxDir() });
    if (test.failed) {
      if (prev !== null) fs.writeFileSync(file, prev);
      else { try { fs.unlinkSync(file); } catch {} }
      throw new Error(`nginx config test failed: ${(test.stderr || test.stdout || '').split('\n').filter((l) => l.includes('emerg') || l.includes('invalid')).join(' ').slice(0, 400)}`);
    }
    await this.ensureRunning();
    // reload config into the running instance
    await runSafe(nginxDir() + '/nginx.exe', ['-p', nginxDir() + '/', '-c', 'conf/nginx.conf', '-s', 'reload'], { cwd: nginxDir() });
    return true;
  },

  async removeVhost(domain) {
    try { fs.unlinkSync(path.join(sitesDir(), `${domain}.conf`)); } catch {}
    await runSafe(nginxDir() + '/nginx.exe', ['-p', nginxDir() + '/', '-c', 'conf/nginx.conf', '-s', 'reload'], { cwd: nginxDir() });
    return true;
  },

  async readLog(domain, kind = 'access', lines = 200) {
    // find the site's log: docroot/../logs under the panel home tree
    const { config: cfg } = await import('../../config.js');
    const homeRoot = path.join(cfg.dataDir, 'home');
    let found = null;
    const walk = (dir, depth) => {
      if (found || depth > 4) return;
      let entries;
      try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
      for (const e of entries) {
        const full = path.join(dir, e.name);
        if (e.isDirectory()) walk(full, depth + 1);
        else if (e.name === `${domain}-${kind}.log`) { found = full; }
      }
    };
    walk(homeRoot, 0);
    if (!found) return '';
    const content = fs.readFileSync(found, 'utf8');
    return content.split('\n').slice(-lines).join('\n');
  },

  async trafficMonth(domain) {
    const text = await this.readLog(domain, 'access', 100000);
    let bytes = 0;
    for (const line of text.split('\n')) {
      const m = line.match(/"\s(\d+)\s"/);
      if (m) bytes += parseInt(m[1], 10) || 0;
    }
    return bytes;
  },

  async test() { return true; }
};
